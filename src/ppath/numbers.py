"""Collect every number quoted in the paper and write them as LaTeX macros."""

from __future__ import annotations

import math
import re
from pathlib import Path


class Numbers:
    def __init__(self) -> None:
        self.values: dict[str, str] = {}

    def add(self, name: str, value, fmt: str = "d") -> None:
        if not re.fullmatch(r"[A-Za-z]+", name):
            raise ValueError(f"macro name must be letters only: {name}")
        if name in self.values:
            raise ValueError(f"duplicate number: {name}")
        if fmt == "s":
            text = str(value)
        else:
            v = float(value) if fmt != "d" else value
            if isinstance(v, float) and not math.isfinite(v):
                raise ValueError(f"non-finite value for {name}: {value}")
            if fmt == "d":
                text = f"{int(value):d}"
            elif fmt == ",":
                text = f"{int(value):,}".replace(",", "{,}")
            else:
                text = format(v, fmt)
                if text in ("-0", "-0.0", "-0.00"):
                    text = text[1:]
        self.values[name] = text

    def write(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        lines = ["% Generated by ppath.pipeline -- do not edit by hand.\n"]
        lines += [f"\\newcommand{{\\n{k[0].upper()}{k[1:]}}}{{{v}}}\n" for k, v in sorted(self.values.items())]
        path.write_text("".join(lines))
